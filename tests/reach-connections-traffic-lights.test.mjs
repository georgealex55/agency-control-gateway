import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createRequire} from "node:module";
const read=p=>readFileSync(new URL("../ghl-gpt-gateway/"+p,import.meta.url),"utf8");
const require=createRequire(new URL("../ghl-gpt-gateway/package.json",import.meta.url));
const ts=require("typescript");
const code=ts.transpileModule(read("lib/reach-connection-traffic-light.ts"),{
 compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}
}).outputText;
const {connectionTrafficLight}=await import("data:text/javascript;base64,"+Buffer.from(code).toString("base64"));
const status=(patch)=>connectionTrafficLight({inventoryReady:true,linkedCount:0,pendingCount:0,statuses:[],explicitExpiredCount:0,...patch});
test("traffic-light statuses are evidence-based and never confuse loading with disconnected",()=>{
 assert.deepEqual(status({inventoryReady:false}),{light:"yellow",label:"Checking status",help:"Account status has not been confirmed yet."});
 assert.equal(status({}).light,"red");
 assert.equal(status({linkedCount:0,pendingCount:1}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:["verified_recently"]}).light,"green");
 assert.equal(status({linkedCount:1,statuses:["expires_soon"]}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:["verification_due"]}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:["expiry_unknown"]}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:["expired"]}).light,"red");
 assert.equal(status({linkedCount:1,statuses:[null]}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:[]}).light,"yellow");
 assert.equal(status({linkedCount:1,statuses:["verified_recently"],explicitExpiredCount:1}).light,"red");
 assert.equal(status({linkedCount:2,statuses:["verified_recently","expired"]}).light,"yellow");
 assert.equal(status({linkedCount:2,statuses:["expired","expired"]}).light,"red");
 assert.equal(status({linkedCount:2,statuses:["verified_recently","verified_recently"],pendingCount:1}).light,"yellow");
 assert.equal(status({linkedCount:2,statuses:["verified_recently","verified_recently"]}).light,"green");
});
test("every available connection gets a labeled traffic light and linked details are closed by default",()=>{
 const page=read("app/connections/page.tsx");
 const css=read("app/connections/connections.css");
 assert.match(page,/connectionTrafficLight\(/);
 assert.match(page,/reach-conn-card-"\+status\.light/);
 assert.match(page,/reach-light-"\+status\.light/);
 assert.match(page,/reach-light-dot "\+status\.light/);
 assert.match(page,/role="status" aria-label=\{p\.name\+": "\+status\.label\}/);
 assert.match(page,/Green: connected/);
 assert.match(page,/Yellow: needs attention/);
 assert.match(page,/Red: disconnected/);
 assert.match(page,/<details className="reach-conn-details"/);
 assert.match(page,/<summary>\{linked\.length\?"Manage connection":"More information"\}<\/summary>/);
 assert.doesNotMatch(page,/<details className="reach-conn-details"[^>]*\sopen[=\s>]/);
 assert.match(page,/linked\.length===0&&pending\.length===0&&<button className="reach-conn-primary"/);
 assert.match(page,/linked\.length>0&&<button type="button"/);
 assert.match(page,/Show only connections needing attention/);
 assert.match(page,/visibleCards=attentionOnly\?cards\.filter\(c=>c\.status\.light!=="green"\)/);
 assert.match(page,/cards\.length===0&&inventory/);
 assert.match(page,/hub\?\.providers\.filter\(p=>/);
 assert.match(page,/m\.launchEnabled\|\|inventory\?\.connections\.some/);
 assert.match(page,/inventory\?\.pending\.some/);
 assert.match(css,/\.reach-light-dot\.green/);
 assert.match(css,/\.reach-light-dot\.yellow/);
 assert.match(css,/\.reach-light-dot\.red/);
 assert.match(css,/\[open\]>summary::after/);
 assert.match(css,/summary:focus-visible/);
 assert.match(css,/@media\(max-width:760px\)/);
 assert.match(page,/Provider was not contacted/);
 assert.match(page,/A green light means access was verified recently/);
 assert.doesNotMatch(page,/NeonCustomerCard|clientSecret|localStorage|sessionStorage|\/api\/platform\/social\/dispatch/);
});
